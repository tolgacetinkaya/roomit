import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const config=JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json','utf8'));
const version=JSON.parse(fs.readFileSync('package.json','utf8')).version;
if(config.version!==version||!/^\d+\.\d+\.\d+$/.test(version))throw Error('Release versions must match and be stable SemVer.');
const directory=`artifacts/releases/v${version}`;fs.mkdirSync(directory,{recursive:true});
const portable=`Roomit-${version}.exe`,setup=`Roomit-${version}-windows-x64-setup.exe`;
const bundle=`target/release/bundle/nsis/Roomit_${version}_x64-setup.exe`;
const signature=fs.readFileSync(bundle+'.sig','utf8').trim();
if(!signature||!Buffer.from(signature,'base64').toString('utf8').includes('signature'))throw Error('Missing updater signature.');
const binary=fs.readFileSync('target/release/roomit.exe');
if(binary.readUInt16LE(binary.readUInt32LE(0x3c)+24+68)!==2)throw Error('Roomit must use the Windows GUI subsystem.');
fs.copyFileSync('target/release/roomit.exe',path.join(directory,portable));
fs.copyFileSync(bundle,path.join(directory,setup));
fs.writeFileSync(path.join(directory,setup+'.sig'),signature+'\n');
const notes=fs.readFileSync(`docs/releases/v${version}.md`,'utf8').trim();
const publishedAt=new Date().toISOString();
const manifest={version,notes,pub_date:publishedAt,platforms:{'windows-x86_64':{signature,url:`https://github.com/tolgacetinkaya/roomit/releases/download/v${version}/${setup}`}}};
fs.writeFileSync(path.join(directory,'latest.json'),JSON.stringify(manifest,null,2)+'\n');
const files=[portable,setup,setup+'.sig','latest.json'];
const sums=files.map(file=>`${createHash('sha256').update(fs.readFileSync(path.join(directory,file))).digest('hex')}  ${file}`).join('\n')+'\n';
fs.writeFileSync(path.join(directory,'SHA256SUMS.txt'),sums);
const provenance={version,sourceCommit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),sourceTree:execFileSync('git',['rev-parse','HEAD^{tree}'],{encoding:'utf8'}).trim(),builtAt:publishedAt,profile:'release',subsystem:'Windows GUI',files:files.map(file=>({file,bytes:fs.statSync(path.join(directory,file)).size,sha256:createHash('sha256').update(fs.readFileSync(path.join(directory,file))).digest('hex')}))};
fs.writeFileSync(path.join(directory,'Roomit-build.json'),JSON.stringify(provenance,null,2)+'\n');
fs.mkdirSync('artifacts/current',{recursive:true});
// Preserve older running executables; publish an unambiguous new versioned name.
fs.copyFileSync(path.join(directory,portable),`artifacts/current/Roomit-${version}-release.exe`);
fs.copyFileSync(path.join(directory,'Roomit-build.json'),'artifacts/current/Roomit-release-build.json');
console.log(JSON.stringify({directory,files:[...files,'SHA256SUMS.txt','Roomit-build.json']},null,2));
